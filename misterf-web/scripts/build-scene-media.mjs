import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(scriptDir, '..');
const repoRoot = path.resolve(webRoot, '..');
const designRoot = path.join(repoRoot, 'design');

const sceneImagesPath = path.join(designRoot, 'scene-images', 'scene-images.json');
const sceneScriptsPath = path.join(designRoot, 'scene-scripts', 'scene-scripts.json');
const publicImageRoot = path.join(webRoot, 'public', 'scene-media', 'images');
const publicAudioRoot = path.join(webRoot, 'public', 'scene-media', 'audio');
const generatedModulePath = path.join(
  webRoot,
  'src',
  'server',
  'sceneMedia',
  'builtInSceneMedia.generated.ts',
);

const sceneImagesRegistry = readJson(sceneImagesPath);
const sceneScriptsRegistry = readJson(sceneScriptsPath);

const approvedImages = new Map(
  sceneImagesRegistry.images
    .filter((image) => image.status === 'approved')
    .map((image) => [image.id, image]),
);

fs.mkdirSync(publicImageRoot, { recursive: true });
fs.rmSync(publicAudioRoot, { force: true, recursive: true });
fs.mkdirSync(publicAudioRoot, { recursive: true });

for (const image of approvedImages.values()) {
  copyFileIfChanged(
    path.join(designRoot, 'scene-images', image.file),
    path.join(publicImageRoot, path.basename(image.file)),
  );
}

const mediaItems = [];

for (const script of sceneScriptsRegistry.scripts) {
  if (script.status !== 'generated') {
    continue;
  }

  const image = approvedImages.get(script.sceneImageId);
  if (!image) {
    continue;
  }

  const audio = script.audio
    ? buildAudioLayer(script.audio, script.speakers)
    : undefined;

  for (const clip of script.audio?.clips ?? []) {
    copyFileIfChanged(
      path.join(designRoot, 'scene-scripts', clip.file),
      path.join(publicAudioRoot, clip.file.replace(/^audio\//, '')),
    );
  }

  const mediaItem = {
    audio,
    format: image.format,
    id: script.id,
    image: {
      alt: buildImageAlt(image),
      height: 1024,
      mediaId: image.id,
      source: 'built_in',
      src: `/public/scene-media/images/${path.basename(image.file)}`,
      width: 1024,
    },
    level: script.level,
    script: buildScript(script),
    setting: image.setting,
    source: 'built_in',
    status: 'ready',
    title: script.title || image.title,
    visualAssetId: image.id,
    visualSummary: image.panelSequence ?? [],
  };
  validateMediaItem(mediaItem);
  mediaItems.push(mediaItem);
}

mediaItems.sort((a, b) => a.id.localeCompare(b.id));

const moduleSource = [
  "import type { SceneMediaLibraryItem } from './types.js';",
  '',
  '// Generated by `npm run build:scene-media`. Do not edit by hand.',
  'export const builtInSceneMediaItems = ',
  `${JSON.stringify(mediaItems, null, 2)} satisfies SceneMediaLibraryItem[];`,
  '',
].join('\n');

fs.writeFileSync(generatedModulePath, moduleSource);

console.log(`Generated ${mediaItems.length} built-in scene media items.`);

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function copyFileIfChanged(sourcePath, destinationPath) {
  fs.mkdirSync(path.dirname(destinationPath), { recursive: true });

  if (
    fs.existsSync(destinationPath) &&
    fs.readFileSync(sourcePath).equals(fs.readFileSync(destinationPath))
  ) {
    return;
  }

  fs.copyFileSync(sourcePath, destinationPath);
}

function buildAudioLayer(audio, speakers = []) {
  const speakerNames = new Map(
    speakers.map((speaker) => [speaker.id, speaker.name]),
  );
  return {
    clips: audio.clips.map((clip) => ({
      speaker: speakerNames.get(clip.speakerId) ?? clip.speakerId,
      src: `/public/scene-media/audio/${clip.file.replace(/^audio\//, '')}`,
      turn: clip.turn,
    })),
    format: audio.format,
    model: audio.model,
    provider: audio.provider,
    voiceStrategy: audio.voiceStrategy,
  };
}

function buildImageAlt(image) {
  const sequence = Array.isArray(image.panelSequence)
    ? image.panelSequence.join(' ')
    : '';
  return sequence ? `${image.title}. ${sequence}` : image.title;
}

function buildScript(script) {
  if (script.scriptType === 'dialogue') {
    const speakerNames = new Map(
      (script.speakers ?? []).map((speaker) => [speaker.id, speaker.name]),
    );

    return {
      identityStrategy: script.identityStrategy,
      scriptType: 'dialogue',
      speakers: (script.speakers ?? []).map((speaker) => ({
        gender: speaker.gender,
        name: speaker.name,
        nameSpokenInAudio: speaker.nameSpokenInAudio,
        role: speaker.role,
      })),
      turns: script.transcript.map((turn) => ({
        speaker: speakerNames.get(turn.speakerId) ?? turn.speakerId,
        text: turn.text,
      })),
    };
  }

  return {
    gender: script.speakers?.[0]?.gender ?? 'neutral',
    identityStrategy: script.identityStrategy,
    scriptType: script.scriptType,
    text: script.transcript.map((turn) => turn.text).join('\n'),
  };
}

function validateMediaItem(item) {
  if (!item.audio || !item.script) {
    return;
  }
  const turns = item.script.scriptType === 'dialogue'
    ? item.script.turns
    : [{ speaker: item.audio.clips[0]?.speaker }];
  if (item.audio.clips.length !== turns.length) {
    throw new Error(`${item.id}: audio clip count does not match script turns.`);
  }
  for (const [index, clip] of item.audio.clips.entries()) {
    if (clip.turn !== index + 1 || clip.speaker !== turns[index]?.speaker) {
      throw new Error(`${item.id}: audio clip ${index + 1} does not match its script turn.`);
    }
  }
}
